export const resolveBrandLogo = (brandOrSlug?: { slug?: string; name?: string; logo?: string } | string | null): string | null => {
  if (!brandOrSlug) return null;
  if (typeof brandOrSlug === "string") {
    const clean = brandOrSlug.toLowerCase().trim();
    return BRAND_LOGOS_MAP[clean] || null;
  }
  if (brandOrSlug.logo && brandOrSlug.logo.trim()) {
    return brandOrSlug.logo.trim();
  }
  const sClean = (brandOrSlug.slug || "").toLowerCase().trim();
  if (BRAND_LOGOS_MAP[sClean]) return BRAND_LOGOS_MAP[sClean];

  const nClean = (brandOrSlug.name || "").toLowerCase().trim().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
  if (BRAND_LOGOS_MAP[nClean]) return BRAND_LOGOS_MAP[nClean];

  return null;
};
